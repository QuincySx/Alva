export function localizeProductText(locale: Locale, value: string | null | undefined): string {
  if (!value) return "";
  if (locale !== "zh-CN") return value;
  const exact = zhTechnicalCopy[value];
  if (exact) return exact;
  if (value === "This Hub session no longer exists.") return "此 Hub 会话已不存在。";
  if (value === "Every worker in this run is archived. Restore one first.") return "此次运行中的所有 Worker 都已归档，请先恢复一个。";
  if (value === "Choose a workspace before running an engine.") return "运行引擎前请先选择工作区。";
  if (value === "This session's pinned model route is unavailable. Restore it in Settings before continuing.") return "此会话固定的模型路由不可用。请先在设置中恢复，再继续。";
  if (value === "Choose an available default model in Settings before starting a session.") return "开始会话前，请先在设置中选择可用的默认模型。";
  if (/^The previous route .+ is unavailable\.$/.test(value)) return value.replace(/^The previous route /, "先前的路由 ").replace(/ is unavailable\.$/, " 不可用。");
  if (/^User explicitly selected /.test(value)) return value.replace(/^User explicitly selected /, "用户明确选择了 ");
  if (/^Skipped /.test(value)) return value.replace(/^Skipped /, "已跳过 ");
  const normalized = value.replaceAll("_", " ");
  return zhTechnicalCopy[normalized] ?? value;
}

export function localizeSystemText(locale: Locale, value: string | null | undefined, fallback: string): string {
  const localized = localizeProductText(locale, value);
  if (locale !== "zh-CN" || !value || localized !== value) return localized;
  return /[A-Za-z]{3,}(?:\s+[A-Za-z]{2,})+/.test(value) ? fallback : localized;
}

function systemLocale(): Locale {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")
    ? "zh-CN"
    : "en-US";
}

function resolvedLocale(preference: LanguagePreference): Locale {
  return preference === "system" ? systemLocale() : preference;
}

function translate(locale: Locale, key: MessageKey, params?: Params) {
  const template = (locale === "zh-CN" ? zh : en)[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

const fallback: I18nValue = {
  locale: "en-US",
  preference: "en-US",
  setPreference: () => {},
  t: (key, params) => translate("en-US", key, params),
  localize: (value) => localizeProductText("en-US", value),
};

const I18nContext = createContext<I18nValue>(fallback);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [preference, setPreference] = useState<LanguagePreference>(() => {
    if (typeof localStorage === "undefined") return "zh-CN";
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === "zh-CN" || stored === "en-US" || stored === "system" ? stored : "zh-CN";
  });
  const locale = resolvedLocale(preference);

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, preference);
    document.documentElement.lang = locale;
    document.title = locale === "zh-CN" ? "ALVA Hub" : "ALVA Hub";
  }, [locale, preference]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    preference,
    setPreference,
    t: (key, params) => translate(locale, key, params),
    localize: (text) => localizeProductText(locale, text),
  }), [locale, preference]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
